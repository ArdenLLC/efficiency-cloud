alter table public.profiles add column if not exists billing_provider text;
alter table public.profiles add column if not exists wallet_payment_method text;


-- Make the task quota respect entitlement expiry even if a cached plan field remains pro.
create or replace function public.enforce_task_plan_limit() returns trigger
language plpgsql security definer set search_path='' as $$
declare v_plan text; v_count integer;
begin
 select case when plan='pro' and subscription_status in ('active','trialing')
   and (current_period_end is null or current_period_end > now()) then 'pro' else 'free' end
 into v_plan from public.profiles where id=new.user_id;
 if coalesce(v_plan,'free') <> 'pro' and new.is_done=false then
  select count(*) into v_count from public.tasks where user_id=new.user_id and is_done=false
   and (tg_op <> 'UPDATE' or id <> new.id);
  if v_count >= 100 then raise exception '免费版最多可保留 100 项未完成任务，升级专业版以提高额度。' using errcode='P0001'; end if;
 end if;
 return new;
end; $$;

create table if not exists public.billing_payments (
  id bigint generated by default as identity primary key,
  stripe_checkout_session_id text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  payment_method text not null check (payment_method in ('alipay','wechat_pay','paypal')),
  status text not null default 'paid' check (status in ('paid','refunded','disputed')),
  period_start timestamptz not null,
  period_end timestamptz not null,
  created_at timestamptz not null default now()
);

-- Expand payment method allow-list for PayPal; safe to re-run.
alter table public.billing_payments drop constraint if exists billing_payments_payment_method_check;
alter table public.billing_payments add constraint billing_payments_payment_method_check
  check (payment_method in ('alipay','wechat_pay','paypal'));

alter table public.billing_payments enable row level security;
drop policy if exists "Users read own billing payments" on public.billing_payments;
create policy "Users read own billing payments" on public.billing_payments for select to authenticated using (auth.uid() = user_id);

create or replace function public.grant_wallet_pro_entitlement(
  p_checkout_session_id text,
  p_user_id uuid,
  p_payment_method text,
  p_days integer default 30
) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  v_start timestamptz;
  v_end timestamptz;
  v_inserted_id bigint;
begin
  if p_payment_method not in ('alipay','wechat_pay','paypal') or p_days < 1 or p_days > 90 then
    raise exception 'Invalid wallet entitlement parameters';
  end if;
  select greatest(coalesce(current_period_end, now()), now()) into v_start
    from public.profiles where id = p_user_id for update;
  if v_start is null then raise exception 'Profile not found'; end if;
  v_end := v_start + make_interval(days => p_days);
  insert into public.billing_payments(stripe_checkout_session_id,user_id,payment_method,status,period_start,period_end)
    values(p_checkout_session_id,p_user_id,p_payment_method,'paid',v_start,v_end)
    on conflict (stripe_checkout_session_id) do nothing
    returning id into v_inserted_id;
  if v_inserted_id is null then return false; end if;
  update public.profiles set plan='pro', subscription_status='active',
    billing_provider='stripe_wallet', wallet_payment_method=p_payment_method,
    current_period_end=v_end, updated_at=now()
    where id=p_user_id;
  return true;
end;
$$;
revoke all on function public.grant_wallet_pro_entitlement(text,uuid,text,integer) from public, anon, authenticated;
grant execute on function public.grant_wallet_pro_entitlement(text,uuid,text,integer) to service_role;
