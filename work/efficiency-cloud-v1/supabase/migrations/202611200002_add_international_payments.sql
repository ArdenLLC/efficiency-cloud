-- Restore international checkout using a merchant-approved provider adapter.
-- No provider credentials or personal payout details belong in client code.
create table if not exists public.intl_payment_orders (
  id bigint generated by default as identity primary key,
  order_no text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  payment_method text not null check (payment_method in ('international_card','paypal')),
  amount_minor integer not null check (amount_minor > 0),
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  status text not null default 'pending' check (status in ('pending','paid','failed','refunded')),
  provider_trade_no text unique,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
alter table public.intl_payment_orders enable row level security;
drop policy if exists "Users read own international payment orders" on public.intl_payment_orders;
create policy "Users read own international payment orders" on public.intl_payment_orders
  for select to authenticated using (auth.uid() = user_id);

create or replace function public.grant_intl_wallet_pro_entitlement(
  p_order_no text, p_user_id uuid, p_payment_method text,
  p_provider_trade_no text, p_days integer default 30
) returns boolean language plpgsql security definer set search_path = '' as $$
declare v_order public.intl_payment_orders%rowtype; v_start timestamptz; v_end timestamptz;
begin
  if p_payment_method not in ('international_card','paypal') or p_days < 1 or p_days > 90 then raise exception 'Invalid entitlement parameters'; end if;
  select * into v_order from public.intl_payment_orders where order_no=p_order_no for update;
  if not found or v_order.user_id <> p_user_id or v_order.payment_method <> p_payment_method then raise exception 'Payment order mismatch'; end if;
  if v_order.status='paid' then return false; end if;
  if v_order.status <> 'pending' then raise exception 'Order is not payable'; end if;
  if exists(select 1 from public.intl_payment_orders where provider_trade_no=p_provider_trade_no and order_no<>p_order_no) then raise exception 'Provider transaction already used'; end if;
  select greatest(coalesce(current_period_end, now()), now()) into v_start from public.profiles where id=p_user_id for update;
  if v_start is null then raise exception 'Profile not found'; end if;
  v_end := v_start + make_interval(days => p_days);
  update public.intl_payment_orders set status='paid',provider_trade_no=p_provider_trade_no,paid_at=now() where order_no=p_order_no;
  update public.profiles set plan='pro',subscription_status='active',billing_provider='international_gateway',wallet_payment_method=p_payment_method,current_period_end=v_end,updated_at=now() where id=p_user_id;
  return true;
end; $$;
revoke all on function public.grant_intl_wallet_pro_entitlement(text,uuid,text,text,integer) from public, anon, authenticated;
grant execute on function public.grant_intl_wallet_pro_entitlement(text,uuid,text,text,integer) to service_role;
